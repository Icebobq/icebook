import type { CoverSource } from './covers'

export type BookStatus = 'unread' | 'reading' | 'finished' | 'paused'

export interface Book {
  id: string
  title: string
  author: string
  categoryId: string
  /** 书脊底色，取自低饱和的旧纸配色 */
  spineColor: string
  /** 书脊文字颜色，深色书脊用 light，浅色（如赭黄）用 dark */
  spineInk: 'light' | 'dark'
  /** 书脊厚度，1 薄 / 2 中 / 3 厚 */
  thickness: 1 | 2 | 3
  price: number
  purchasedAt: string
  readCount: number
  finishCount: number
  pages: number
  currentPage: number
  status: BookStatus
  rating: number
  blurb: string
  /** 真实封面图地址；拿不到时留空，界面回落到合成书脊 */
  coverUrl?: string
  /** 封面来源，便于区分自动抓取与手动填写 */
  coverSource?: CoverSource
  isbn?: string
  /** 最近一次尝试抓取封面的日期，避免对失败的书反复请求 */
  coverCheckedAt?: string
}

